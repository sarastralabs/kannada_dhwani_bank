/** 3.5 -> "೩.೫" (Kannada digits). */
export function kannadaDigits(value: string | number): string {
  return String(value).replace(/\d/g, (d) => "೦೧೨೩೪೫೬೭೮೯"[Number(d)]);
}

export function rateLabel(percent: number): string {
  return `ಶೇ. ${kannadaDigits(Number.isInteger(percent) ? percent : percent.toString())}`;
}
